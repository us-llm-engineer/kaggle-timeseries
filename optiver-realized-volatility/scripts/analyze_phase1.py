import numpy as np, pandas as pd, os
R=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d=pd.read_parquet(f"{R}/results/phase1_profile.parquet")
pd.set_option("display.width",200)
print("rows",len(d),"stocks",d.stock_id.nunique(),"time_ids",d.time_id.nunique())
print("target NA",d.target.isna().sum(),"profile NA(rv_all)",d.rv_all.isna().sum())
print(d.target.describe(percentiles=[.01,.25,.5,.75,.99]).round(5).to_string())
print("skew",d.target.skew().round(2),"log-target skew",np.log(d.target).skew().round(2))
tp=d.groupby("stock_id").size(); print("time_ids per stock: min",tp.min(),"median",tp.median(),"max",tp.max())
print("book rows/bucket: median",d.n_book.median(),"frac<600:",(d.n_book<600).mean().round(3),"frac max_sec<599:",(d.max_sec<599).mean().round(3))
print("buckets with 0 trades:",(d.n_trade==0).mean().round(4),"median trades",d.n_trade.median())
def rmspe(y,p): return float(np.sqrt(np.mean(((y-p)/y)**2)))
y=d.target.values
print("RMSPE naive rv_all:",round(rmspe(y,d.rv_all.values),4))
print("RMSPE naive rv_late:",round(rmspe(y,d.rv_late.values),4))
k=(y*d.rv_all/ (d.rv_all**2)).mean()
# best constant scale for RMSPE: minimise mean((1-c*p/y)^2) -> c = mean(p/y)/mean((p/y)^2)
q=(d.rv_all/d.target); c=q.mean()/(q**2).mean(); print("best scalar c",round(c,3),"RMSPE",round(rmspe(y,c*d.rv_all.values),4))
print("RMSPE global-median constant:",round(rmspe(y,np.full_like(y,np.median(y))),4))
sm=d.groupby("stock_id").target.transform("median"); print("RMSPE per-stock median:",round(rmspe(y,sm.values),4))
print("corr(log target, log rv_all):",np.corrcoef(np.log(y),np.log(d.rv_all.clip(1e-9)))[0,1].round(3))
print("corr(log target, log rv_late):",np.corrcoef(np.log(y),np.log(d.rv_late.clip(1e-9)))[0,1].round(3))
st=d.groupby("stock_id").target.agg(["median","std","count"]); print("per-stock median target: min %.5f max %.5f ratio %.1f"%(st['median'].min(),st['median'].max(),st['median'].max()/st['median'].min()))
tm=d.groupby("time_id").target.agg(["mean","count"]); print("time_id cross-section: stocks per time_id median",tm['count'].median())
lt=np.log(d.target); tmean=lt.groupby(d.time_id).transform("mean"); print("share of log-target variance explained by time_id market factor:",round(1-((lt-tmean)**2).sum()/((lt-lt.mean())**2).sum(),3))
print("time_id sorted by mean target, autocorr of adjacent ids (ids are shuffled if ~0):",round(tm['mean'].sort_index().autocorr(1),3))
